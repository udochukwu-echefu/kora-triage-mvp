from __future__ import annotations

from dataclasses import dataclass
from typing import Iterable


@dataclass(frozen=True)
class GoldCase:
    case_id: str
    domain: str
    language: str
    channel: str
    message: str
    intent: str
    urgency: str
    route: str
    entities: dict[str, str | None]
    subject: str | None = None


def _scenario(
    *,
    key: str,
    domain: str,
    languages: tuple[str, str, str, str],
    channel: str,
    messages: tuple[str, str, str, str],
    intent: str,
    urgency: str,
    route: str,
    entities: dict[str, str | None],
    subject: str | None = None,
) -> list[GoldCase]:
    return [
        GoldCase(
            case_id=f"EVAL-{key}-{index + 1:02d}",
            domain=domain,
            language=languages[index],
            channel=channel,
            message=message,
            intent=intent,
            urgency=urgency,
            route=route,
            entities=entities,
            subject=subject,
        )
        for index, message in enumerate(messages)
    ]


