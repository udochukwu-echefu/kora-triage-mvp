GOLD_CASES: tuple[GoldCase, ...] = tuple(
    case for scenario in _SCENARIOS for case in scenario
)


def dataset_summary(cases: Iterable[GoldCase] = GOLD_CASES) -> dict:
    items = list(cases)
    return {
        "cases": len(items),
        "domains": sorted({item.domain for item in items}),
        "intents": sorted({item.intent for item in items}),
        "routes": sorted({item.route for item in items}),
        "channels": {
            channel: sum(item.channel == channel for item in items)
            for channel in sorted({item.channel for item in items})
        },
        "languages": {
            language: sum(item.language == language for item in items)
            for language in sorted({item.language for item in items})
        },
    }


assert len(GOLD_CASES) == 100
